"""The record of the API (task 1.9.5): the OpenAPI document and a table of every endpoint, written to `docs/`.

`docs/openapi.json` is the machine-readable contract (a typed client for the app can be generated from it) and
`docs/api-contract.md` is the same thing as a table people can read. Both are produced from the running app by
`python scripts/export_api_contract.py`, and `tests/test_api_contract.py` fails when either file no longer matches the
code, so the record cannot drift: adding or changing an endpoint means regenerating and committing them.
"""

import json
from typing import Any

HTTP_METHODS = ("get", "put", "post", "patch", "delete")
TITLE = "UOMi API"  # the app's own name setting must not change the record


def normalised(schema: dict[str, Any]) -> dict[str, Any]:
    """The schema as plain JSON, with the title fixed so a developer's own settings cannot change the file."""
    plain = json.loads(json.dumps(schema))
    plain["info"] = {"title": TITLE, "version": plain.get("info", {}).get("version", "")}
    return plain


def contract_json(schema: dict[str, Any]) -> str:
    return json.dumps(normalised(schema), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _schema_name(schema: dict[str, Any] | None) -> str:
    """'Foo' for a reference to Foo, 'list[Foo]' for a list of them, '' when there is nothing."""
    if not schema:
        return ""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        inner = _schema_name(schema.get("items"))
        return f"list[{inner}]" if inner else "list"
    if "anyOf" in schema:
        return " or ".join(name for name in (_schema_name(part) for part in schema["anyOf"]) if name and name != "null")
    return schema.get("type", "")


def _body(operation: dict[str, Any]) -> str:
    content = operation.get("requestBody", {}).get("content", {})
    return _schema_name(next(iter(content.values()), {}).get("schema")) if content else ""


def _success(operation: dict[str, Any]) -> str:
    codes = sorted(code for code in operation.get("responses", {}) if code.startswith("2"))
    if not codes:
        return ""
    content = operation["responses"][codes[0]].get("content", {})
    shape = _schema_name(next(iter(content.values()), {}).get("schema")) if content else ""
    return f"{codes[0]} {shape}".strip()


def _first_line(text: str) -> str:
    return " ".join(text.strip().splitlines()[0].split()) if text and text.strip() else ""


def operations(schema: dict[str, Any]) -> list[dict[str, str]]:
    """One row per endpoint, in a stable order: by tag, then path, then method."""
    rows = []
    for path, item in schema.get("paths", {}).items():
        for method in HTTP_METHODS:
            operation = item.get(method)
            if operation is None:
                continue
            query = [p["name"] for p in operation.get("parameters", []) if p.get("in") == "query"]
            rows.append(
                {
                    "tag": (operation.get("tags") or ["meta"])[0],
                    "method": method.upper(),
                    "path": path,
                    "signed_in": "yes" if operation.get("security") else "no",
                    "body": _body(operation),
                    "query": ", ".join(query),
                    "success": _success(operation),
                    "summary": _first_line(operation.get("description", "")),
                }
            )
    return sorted(rows, key=lambda row: (row["tag"], row["path"], HTTP_METHODS.index(row["method"].lower())))


def contract_markdown(schema: dict[str, Any]) -> str:
    rows = operations(normalised(schema))
    lines = [
        "# UOMi API contract",
        "",
        "Generated by `python scripts/export_api_contract.py` from the running app. **Do not edit by hand.** The same",
        "information in machine-readable form is in [`openapi.json`](openapi.json); generate a typed client for the app",
        "from that (for example `npx openapi-typescript docs/openapi.json -o mobile/src/services/server/api-types.ts`).",
        "`tests/test_api_contract.py` fails when this file or `openapi.json` no longer matches the code.",
        "",
        f"{len(rows)} endpoints. Errors use the envelope in [`backend-api.md`](backend-api.md) (`{{\"detail\": {{\"code\", \"message\", ...}}}}`).",
        "",
    ]
    current = None
    for row in rows:
        if row["tag"] != current:
            current = row["tag"]
            lines += [f"## {current}", "", "| Method | Path | Signed in | Body | Query | Success | What it does |", "|---|---|---|---|---|---|---|"]
        cells = [row["method"], f"`{row['path']}`", row["signed_in"], row["body"] or "-", row["query"] or "-", row["success"] or "-", row["summary"] or "-"]
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
        nxt = rows[rows.index(row) + 1] if rows.index(row) + 1 < len(rows) else None
        if nxt is None or nxt["tag"] != current:
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
